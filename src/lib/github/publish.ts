import "server-only";
import * as diff from "diff";

export interface PublishResult {
  success: boolean;
  needsConfirmation?: boolean;
  diff?: string;
  sha?: string;
  commitUrl?: string;
  contentUrl?: string;
  error?: string;
}

export interface PublishOptions {
  token: string;
  login: string;
  markdown: string;
  commitMessage?: string;
  confirmOverwrite?: boolean;
}

const GITHUB_API = "https://api.github.com";

function getHeaders(token: string) {
  return {
    Authorization: `Bearer ${token}`,
    Accept: "application/vnd.github.v3+json",
    "User-Agent": "Hello-md-Profile-Generator",
  };
}

/**
 * Ensures the target username/username repository exists.
 * If not found, creates it via POST /user/repos with auto_init: true.
 */
async function ensureRepositoryExists(token: string, login: string): Promise<void> {
  const repoRes = await fetch(`${GITHUB_API}/repos/${login}/${login}`, {
    headers: getHeaders(token),
  });

  if (repoRes.status === 404) {
    // Create the special profile repository
    const createRes = await fetch(`${GITHUB_API}/user/repos`, {
      method: "POST",
      headers: {
        ...getHeaders(token),
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        name: login,
        description: "GitHub Profile README generated by Hello-md",
        private: false,
        auto_init: true,
      }),
    });

    if (!createRes.ok) {
      const errJson = await createRes.json().catch(() => ({}));
      throw new Error(
        `Failed to create repository ${login}/${login}: ${
          errJson.message || createRes.statusText
        }`
      );
    }

    // Give GitHub's internal database a moment to initialize the new repository
    await new Promise((resolve) => setTimeout(resolve, 1500));
  } else if (!repoRes.ok) {
    const errJson = await repoRes.json().catch(() => ({}));
    throw new Error(
      `Failed to access repository ${login}/${login}: ${
        errJson.message || repoRes.statusText
      }`
    );
  }
}

/**
 * Fetch existing README content and sha if it exists
 */
async function fetchExistingReadme(
  token: string,
  login: string
): Promise<{ sha?: string; content?: string } | null> {
  const res = await fetch(`${GITHUB_API}/repos/${login}/${login}/contents/README.md`, {
    headers: getHeaders(token),
  });

  if (res.status === 404) {
    return null;
  }

  if (!res.ok) {
    const errJson = await res.json().catch(() => ({}));
    throw new Error(
      `Failed to fetch README.md from ${login}/${login}: ${
        errJson.message || res.statusText
      }`
    );
  }

  const data = await res.json();
  const rawContent = data.content
    ? Buffer.from(data.content, "base64").toString("utf-8")
    : "";

  return {
    sha: data.sha,
    content: rawContent,
  };
}

/**
 * Computes a unified diff between current and new README markdown
 */
export function computeReadmeDiff(oldContent: string, newContent: string): string {
  return diff.createTwoFilesPatch(
    "current/README.md",
    "new/README.md",
    oldContent,
    newContent,
    "Current GitHub README",
    "Generated Hello-md README"
  );
}

/**
 * Main publishing flow:
 * 1. Ensure repo exists (creates if not found)
 * 2. Check for existing README.md
 * 3. If exists and confirmOverwrite !== true, return unified diff for user confirmation
 * 4. Commit via PUT /repos/{login}/{login}/contents/README.md
 */
export async function publishReadmeToGithub(options: PublishOptions): Promise<PublishResult> {
  const { token, login, markdown, commitMessage, confirmOverwrite } = options;

  if (!token) {
    throw new Error("Missing GitHub authentication token");
  }
  if (!login) {
    throw new Error("Missing target GitHub username");
  }
  if (!markdown) {
    throw new Error("Markdown content cannot be empty");
  }

  // 1. Ensure the repo login/login exists
  await ensureRepositoryExists(token, login);

  // 2. Fetch existing README
  const existing = await fetchExistingReadme(token, login);

  // 3. If existing README is present and not yet confirmed, require confirmation
  if (existing && existing.content && !confirmOverwrite) {
    // Only require confirmation if content has actually changed
    if (existing.content.trim() !== markdown.trim()) {
      const unifiedDiff = computeReadmeDiff(existing.content, markdown);
      return {
        success: false,
        needsConfirmation: true,
        diff: unifiedDiff,
        sha: existing.sha,
      };
    }
  }

  // 4. Commit the new README.md
  const message = commitMessage?.trim() || "docs: update GitHub profile README.md via Hello-md";
  const base64Content = Buffer.from(markdown, "utf-8").toString("base64");

  const putBody: Record<string, unknown> = {
    message,
    content: base64Content,
  };

  if (existing?.sha) {
    putBody.sha = existing.sha;
  }

  const putRes = await fetch(`${GITHUB_API}/repos/${login}/${login}/contents/README.md`, {
    method: "PUT",
    headers: {
      ...getHeaders(token),
      "Content-Type": "application/json",
    },
    body: JSON.stringify(putBody),
  });

  if (!putRes.ok) {
    const errJson = await putRes.json().catch(() => ({}));
    throw new Error(
      `Failed to commit README.md to ${login}/${login}: ${
        errJson.message || putRes.statusText
      }`
    );
  }

  const putData = await putRes.json();
  const commitUrl =
    putData.commit?.html_url || `https://github.com/${login}/${login}/commits/main`;
  const contentUrl =
    putData.content?.html_url || `https://github.com/${login}/${login}/blob/main/README.md`;

  return {
    success: true,
    commitUrl,
    contentUrl,
  };
}
